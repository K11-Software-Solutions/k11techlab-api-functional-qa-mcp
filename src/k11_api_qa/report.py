"""Reports: Markdown (PR comment / step summary), JSON (full evidence), JUnit XML (CI dashboards)."""

from __future__ import annotations

import json
from dataclasses import asdict
from datetime import datetime, timezone
from pathlib import Path
from xml.sax.saxutils import escape, quoteattr

from . import __version__
from .runner import FlowResult

ICON = {"passed": "✅", "failed": "❌", "blocked": "⛔", "error": "⚠️", "skipped": "⏭️"}


def counts(results: list[FlowResult]) -> dict:
    c = {"flows": len(results), "passed": 0, "failed": 0, "blocked": 0, "error": 0}
    for r in results:
        c[r.status] = c.get(r.status, 0) + 1
    steps = [s for r in results for s in r.steps if not s.cleanup]
    c["steps"] = len(steps)
    c["server_errors"] = sum(1 for s in steps if s.response and isinstance(s.response.get("status"), int) and s.response["status"] >= 500)
    return c


def to_dict(results: list[FlowResult], environment: str) -> dict:
    return {"tool": f"k11-api-functional-qa-mcp {__version__}",
            "generatedAt": datetime.now(timezone.utc).isoformat(timespec="seconds"),
            "environment": environment, "summary": counts(results), "flows": [asdict(r) for r in results]}


def to_markdown(results: list[FlowResult], environment: str) -> str:
    c = counts(results)
    head = "✅ All flows passed" if c["passed"] == c["flows"] and c["flows"] else "❌ Some flows did not pass"
    L = [f"## API functional tests: {head}", "",
         f"Environment **{environment}**: {c['flows']} flow(s), **{c['passed']} passed**, {c['failed']} failed, "
         f"{c['blocked']} blocked, {c['error']} errors; {c['steps']} steps"
         + (f"; **{c['server_errors']} server error(s) (5xx)**" if c["server_errors"] else "") + ".", ""]
    L += ["| Flow | Result | Steps | Time |", "|---|---|---|---|"]
    for r in results:
        main = [s for s in r.steps if not s.cleanup]
        L.append(f"| {r.name} | {ICON.get(r.status, '')} {r.status} | {sum(s.status == 'passed' for s in main)}/{len(main)} | {r.ms} ms |")
    L.append("")
    for r in results:
        if r.status == "passed":
            continue
        L += [f"### {ICON.get(r.status, '')} {r.name}", f"`{r.file}`" if r.file else "", ""]
        if r.error:
            L += [f"> {r.error}", ""]
        for s in r.steps:
            if s.status == "passed":
                continue
            L.append(f"- **{s.name}**{' (cleanup)' if s.cleanup else ''}: {s.status}")
            if s.error:
                L.append(f"  - {s.error}")
            if s.request:
                L.append(f"  - request: `{s.request['method']} {s.request['url']}`")
            if s.response and "status" in s.response:
                L.append(f"  - response: HTTP {s.response['status']} in {s.response.get('ms')} ms")
            if s.query:
                L.append(f"  - query on `{s.query['database']}`: `{' '.join(s.query['sql'].split())[:160]}`")
            for a in s.assertions:
                if not a["ok"]:
                    L.append(f"  - ✗ {a['check']}" + (f": {a['detail']}" if a.get("detail") else ""))
        warns = [(s.name, a) for s in r.steps for a in s.assertions if a.get("warn")]
        for name, a in warns[:5]:
            L.append(f"- ⚠ {name}: {a['detail']}")
        L.append("")
    L.append(f"<sub>Generated by k11-api-functional-qa-mcp {__version__}. Full request/response evidence: "
             "api-test-report.json.</sub>")
    return "\n".join(L) + "\n"


def to_junit(results: list[FlowResult]) -> str:
    c = counts(results)
    out = ['<?xml version="1.0" encoding="UTF-8"?>',
           f'<testsuites name="api-functional" tests="{c["flows"]}" failures="{c["failed"] + c["blocked"]}" errors="{c["error"]}">']
    for r in results:
        main = [s for s in r.steps if not s.cleanup]
        fails = sum(s.status in ("failed", "blocked") for s in main)
        errs = sum(s.status == "error" for s in main) + (1 if r.error else 0)
        out.append(f'  <testsuite name={quoteattr(r.name)} tests="{len(main) or 1}" failures="{fails}" errors="{errs}" '
                   f'time="{r.ms / 1000:.3f}">')
        if r.error and not main:
            out.append(f'    <testcase name="load" classname={quoteattr(r.file or r.name)}><error message={quoteattr(r.error)}/></testcase>')
        for s in main:
            out.append(f'    <testcase name={quoteattr(s.name)} classname={quoteattr(r.file or r.name)} time="{(s.ms or 0) / 1000:.3f}">')
            failed = [a for a in s.assertions if not a["ok"]]
            if s.status == "failed":
                msg = "; ".join(f"{a['check']}: {a.get('detail', '')}" for a in failed) or (s.error or "failed")
                out.append(f"      <failure message={quoteattr(msg[:500])}>{escape(json.dumps(s.response or {}, default=str)[:2000])}</failure>")
            elif s.status in ("blocked", "error"):
                tag = "failure" if s.status == "blocked" else "error"
                out.append(f"      <{tag} message={quoteattr((s.error or s.status)[:500])}/>")
            out.append("    </testcase>")
        out.append("  </testsuite>")
    out.append("</testsuites>")
    return "\n".join(out) + "\n"


def write(results: list[FlowResult], environment: str, out_dir: Path) -> dict[str, Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    paths = {"markdown": out_dir / "api-test-report.md", "json": out_dir / "api-test-report.json",
             "junit": out_dir / "api-test-junit.xml"}
    paths["markdown"].write_text(to_markdown(results, environment), "utf8")
    paths["json"].write_text(json.dumps(to_dict(results, environment), indent=2, ensure_ascii=False, default=str) + "\n", "utf8")
    paths["junit"].write_text(to_junit(results), "utf8")
    return paths
